CREATE TABLE IF NOT EXISTS tbPlanoSeguranca (
  idPlano INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  idUsuario INT UNSIGNED NOT NULL UNIQUE,
  contatos TEXT NOT NULL,
  locaisSeguros TEXT NOT NULL,
  passos TEXT NOT NULL,
  atualizadoEm DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (idUsuario) REFERENCES tbUsuario(idUsuario) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tbCheckin (
  idCheckin INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  idUsuario INT UNSIGNED NOT NULL UNIQUE,
  intervaloHoras TINYINT UNSIGNED NOT NULL,
  observacao VARCHAR(300) NOT NULL,
  proximoEm DATETIME(3) NOT NULL,
  confirmadoEm DATETIME(3) NULL,
  atualizadoEm DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (idUsuario) REFERENCES tbUsuario(idUsuario) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tbPermissaoLocalizacao (
  idPermissao INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  idUsuario INT UNSIGNED NOT NULL,
  idContaGuardiao INT UNSIGNED NOT NULL,
  permitido BOOLEAN NOT NULL DEFAULT TRUE,
  atualizadoEm DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_permissao_localizacao (idUsuario, idContaGuardiao),
  FOREIGN KEY (idUsuario) REFERENCES tbUsuario(idUsuario) ON DELETE CASCADE,
  FOREIGN KEY (idContaGuardiao) REFERENCES tbUsuario(idUsuario) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tbSosReconhecimento (
  idAlertaSos INT UNSIGNED PRIMARY KEY,
  idContaGuardiao INT UNSIGNED NOT NULL,
  confirmadoEm DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (idAlertaSos) REFERENCES tbAlertaSos(idAlertaSos) ON DELETE CASCADE,
  FOREIGN KEY (idContaGuardiao) REFERENCES tbUsuario(idUsuario) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
